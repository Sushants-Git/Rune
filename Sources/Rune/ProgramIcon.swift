    /// Match a process's command line, argv[0] first.
    ///
    /// Only the command's own name, unlike `AgentIcon`: agents hide behind a
    /// runtime wrapper and need their install path sniffed, while everything
    /// here is a binary you type the name of.
    static func detect(arguments: [String]) -> ProgramIcon? {
        guard let first = arguments.first else { return nil }
        var name = (first as NSString).lastPathComponent.lowercased()
        // `-fish` and `-zsh`: a login shell is argv[0] with a leading dash.
        if name.hasPrefix("-") { name.removeFirst() }
        return allCases.first { $0.matches(name) }
    }

    private func matches(_ name: String) -> Bool {
        switch self {
        case .neovim: ["nvim", "neovim"].contains(name)
        case .vim: ["vim", "vi"].contains(name)
        // The binary is `hx`; nothing on disk is called helix.
        case .helix: ["hx", "helix"].contains(name)
        case .tmux: ["tmux"].contains(name)
        case .emacs: ["emacs", "emacsclient"].contains(name)
        case .docker: ["docker", "docker-compose", "lazydocker"].contains(name)
        // k9s has no mark of its own, so it flies the Kubernetes one.
        case .kubernetes: ["k9s", "kubectl"].contains(name)
        case .postgres: ["psql", "pgcli"].contains(name)
        // Plus any `python`, `python3`, `python3.12` — see `matches`.
        case .python: name.hasPrefix("python") || name == "ipython"
        // lazygit ships no SVG; the Git mark reads correctly for all three.
        case .git: ["lazygit", "tig", "gitui"].contains(name)
        case .mysql: ["mysql", "mycli"].contains(name)
        case .sqlite: ["sqlite3", "sqlite"].contains(name)
        case .terraform: ["terraform"].contains(name)
        case .aws: ["aws"].contains(name)
        case .gcloud: ["gcloud"].contains(name)
        case .pnpm: ["pnpm"].contains(name)
        case .cargo: ["cargo", "rustc"].contains(name)
        // Exact match only: `go` is two letters and prefixes far too much.
        case .go: name == "go"
        case .gemini: ["gemini"].contains(name)
        case .copilot: ["copilot"].contains(name)
        case .ruby: ["irb", "ruby", "pry"].contains(name)
        case .php: ["php", "artisan"].contains(name)
        case .lua: ["lua", "luajit"].contains(name)
        case .fish: ["fish"].contains(name)
        case .starship: ["starship"].contains(name)
        case .htop: ["htop"].contains(name)
        }
    }

    /// Shells and prompts, which are the foreground process of *every* idle
    /// terminal. Shown only when the workspace has nothing better to offer —
    /// otherwise a fish user's every row would be a fish, and the project
    /// icons they were reading before would all disappear.
    var isAmbient: Bool {
        switch self {
        case .fish, .starship: true
        default: false
        }
    }

